    @classmethod
    def get(cls, key: str, lang: str = "es") -> str:
        """Obtiene una traducción con soporte para fallback de variaciones de idioma."""
        if key not in cls.TRANSLATIONS:
            return key
        
        translations = cls.TRANSLATIONS[key]
        if lang in translations:
            return translations[lang]
        
        base_lang = lang.split("-")[0]
        if base_lang in translations:
            return translations[base_lang]
            
        return translations.get("es", translations.get("en", key))
    
    @classmethod
    def set_language(cls, lang: str) -> bool:
        """Valida que el idioma sea soportado."""
        return lang in cls.LANGUAGES

    @classmethod
    def get_literal(cls, text: str, lang: str = "es") -> str:
        """Traduce textos literales heredados que todavía no usan claves i18n."""
        if not isinstance(text, str) or not text:
            return text
        translations = getattr(cls, "LITERAL_TRANSLATIONS", {}).get(text)
        if not translations:
            return text
        if lang in translations:
            return translations[lang]
        base_lang = lang.split("-")[0]
        if base_lang in translations:
            return translations[base_lang]
        return translations.get("es", text)


